import { useState } from 'react';
import { Button } from '../ui/button';
import { Alert, AlertDescription, AlertTitle } from '../ui/alert';
import { Progress } from '../ui/progress';
import { Upload, CheckCircle, XCircle, Shield, AlertTriangle, Eye, Brain } from 'lucide-react';
import { projectId, publicAnonKey } from '../../utils/supabase/info';
import { isDemoMode } from '../../src/env';
import { demoService } from '../../utils/demoService';

interface ImageUploadProps {
  onImageUploaded: (imageData: { fileName: string; signedUrl: string }) => void;
  issueId: string;
}

interface VerificationResult {
  isAIGenerated: boolean;
  isFromInternet: boolean;
  confidence: number;
  details: any;
}

export function ImageUploadWithVerification({ onImageUploaded, issueId }: ImageUploadProps) {
  const [uploading, setUploading] = useState(false);
  const [verifying, setVerifying] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [verificationResult, setVerificationResult] = useState<VerificationResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [success, setSuccess] = useState(false);

  const handleFileSelect = async (event: React.ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;

    // Reset states
    setError(null);
    setSuccess(false);
    setVerificationResult(null);
    setUploading(true);
    setVerifying(true);
    setUploadProgress(0);

    try {
      // Create form data
      const formData = new FormData();
      formData.append('image', file);
      formData.append('issueId', issueId);

      // Simulate progress during verification
      const progressInterval = setInterval(() => {
        setUploadProgress(prev => {
          if (prev >= 90) {
            clearInterval(progressInterval);
            return 90;
          }
          return prev + 10;
        });
      }, 200);

      let result;

      if (isDemoMode) {
        // Use demo service
        result = await demoService.uploadImage(file, issueId);
        clearInterval(progressInterval);
        setUploadProgress(100);
      } else {
        // Use real Supabase backend
        const response = await fetch(
          `https://${projectId}.supabase.co/functions/v1/make-server-9c2b6e13/upload-image`,
          {
            method: 'POST',
            headers: {
              'Authorization': `Bearer ${publicAnonKey}`,
            },
            body: formData,
          }
        );

        clearInterval(progressInterval);
        setUploadProgress(100);

        result = await response.json();

        if (!response.ok) {
          // Handle verification failure
          if (result.verification) {
            setVerificationResult(result.verification);
          }
          throw new Error(result.error || 'Upload failed');
        }
      }

      // Success
      setVerificationResult(result.verification);
      setSuccess(true);
      onImageUploaded({
        fileName: result.fileName,
        signedUrl: result.signedUrl
      });

    } catch (err) {
      console.error('Upload error:', err);
      setError(err instanceof Error ? err.message : 'Upload failed');
    } finally {
      setUploading(false);
      setVerifying(false);
    }
  };

  const getVerificationIcon = () => {
    if (!verificationResult) return null;
    
    if (verificationResult.isAIGenerated) {
      return <Brain className="h-5 w-5 text-red-500" />;
    }
    
    if (verificationResult.isFromInternet) {
      return <Eye className="h-5 w-5 text-orange-500" />;
    }
    
    return <Shield className="h-5 w-5 text-green-500" />;
  };

  const getVerificationMessage = () => {
    if (!verificationResult) return null;
    
    if (verificationResult.isAIGenerated) {
      return {
        title: "AI-Generated Content Detected",
        description: "This image appears to be generated by AI. Please upload an authentic photograph of the issue.",
        type: "destructive" as const
      };
    }
    
    if (verificationResult.isFromInternet) {
      return {
        title: "Internet Source Detected",
        description: "This image was found on the internet. Please upload an original photograph you took yourself.",
        type: "destructive" as const
      };
    }
    
    return {
      title: "Image Verified",
      description: "This appears to be an authentic, original photograph. Upload successful!",
      type: "default" as const
    };
  };

  return (
    <div className="space-y-4">
      {/* Upload Area */}
      <div className="border-2 border-dashed border-[#475569] rounded-lg p-8 text-center hover:border-blue-500 transition-colors">
        <input
          type="file"
          accept="image/*,video/*"
          onChange={handleFileSelect}
          className="hidden"
          id="image-upload"
          disabled={uploading}
        />
        <label htmlFor="image-upload" className={`cursor-pointer ${uploading ? 'pointer-events-none' : ''}`}>
          <div className="flex flex-col items-center space-y-4">
            {uploading ? (
              <div className="w-12 h-12 border-4 border-blue-500 border-t-transparent rounded-full animate-spin"></div>
            ) : (
              <Upload className="h-12 w-12 text-gray-400" />
            )}
            
            <div>
              <p className="text-white mb-2">
                {uploading ? 'Processing...' : 'Click to upload or drag and drop'}
              </p>
              <p className="text-gray-400 text-sm">
                Images and videos only • Maximum 10MB
              </p>
              <p className="text-gray-400 text-xs mt-1">
                ⚠️ AI-generated or internet images will be rejected
              </p>
            </div>
          </div>
        </label>
      </div>

      {/* Progress Bar */}
      {uploading && (
        <div className="space-y-2">
          <div className="flex justify-between text-sm">
            <span className="text-gray-300">
              {verifying ? 'Verifying authenticity...' : 'Uploading...'}
            </span>
            <span className="text-gray-300">{uploadProgress}%</span>
          </div>
          <Progress value={uploadProgress} className="h-2" />
          
          {verifying && (
            <div className="text-center">
              <div className="flex items-center justify-center space-x-2 text-blue-400">
                <Shield className="h-4 w-4 animate-pulse" />
                <span className="text-sm">Running AI detection and reverse image search...</span>
              </div>
            </div>
          )}
        </div>
      )}

      {/* Verification Results */}
      {verificationResult && (
        <Alert className={`${
          verificationResult.isAIGenerated || verificationResult.isFromInternet
            ? 'border-red-500 bg-red-500/10'
            : 'border-green-500 bg-green-500/10'
        }`}>
          <div className="flex items-center space-x-2">
            {getVerificationIcon()}
            <div className="flex-1">
              <AlertTitle className="text-white">
                {getVerificationMessage()?.title}
              </AlertTitle>
              <AlertDescription className="text-gray-300">
                {getVerificationMessage()?.description}
              </AlertDescription>
            </div>
          </div>
          
          {/* Verification Details */}
          <div className="mt-3 p-3 bg-black/30 rounded text-xs">
            <p className="text-gray-400 mb-1">Verification Details:</p>
            <div className="grid grid-cols-2 gap-2">
              <div>
                <span className="text-gray-300">AI Detection:</span>
                <span className={`ml-1 ${verificationResult.isAIGenerated ? 'text-red-400' : 'text-green-400'}`}>
                  {verificationResult.isAIGenerated ? 'Failed' : 'Passed'}
                </span>
              </div>
              <div>
                <span className="text-gray-300">Internet Check:</span>
                <span className={`ml-1 ${verificationResult.isFromInternet ? 'text-orange-400' : 'text-green-400'}`}>
                  {verificationResult.isFromInternet ? 'Found Online' : 'Original'}
                </span>
              </div>
            </div>
            {verificationResult.confidence > 0 && (
              <div className="mt-1">
                <span className="text-gray-300">Confidence:</span>
                <span className="ml-1 text-white">{(verificationResult.confidence * 100).toFixed(1)}%</span>
              </div>
            )}
          </div>
        </Alert>
      )}

      {/* Error Alert */}
      {error && (
        <Alert className="border-red-500 bg-red-500/10">
          <XCircle className="h-4 w-4" />
          <AlertTitle className="text-white">Upload Failed</AlertTitle>
          <AlertDescription className="text-gray-300">
            {error}
          </AlertDescription>
        </Alert>
      )}

      {/* Success Alert */}
      {success && (
        <Alert className="border-green-500 bg-green-500/10">
          <CheckCircle className="h-4 w-4" />
          <AlertTitle className="text-white">Upload Successful</AlertTitle>
          <AlertDescription className="text-gray-300">
            Your image has been verified and uploaded successfully.
          </AlertDescription>
        </Alert>
      )}

      {/* Information Box */}
      <div className="bg-[#334155] rounded-lg p-4">
        <h4 className="text-white font-medium mb-2 flex items-center">
          <Shield className="h-4 w-4 mr-2" />
          Image Verification Process
        </h4>
        <div className="text-sm text-gray-300 space-y-1">
          <p>• AI Detection: Checks if the image was generated by AI tools</p>
          <p>• Reverse Image Search: Verifies the image isn't from the internet</p>
          <p>• Authenticity Validation: Ensures original, real-world photography</p>
        </div>
      </div>
    </div>
  );
}